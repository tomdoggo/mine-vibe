/** 各位置的能力值偏移（相对目标值） */
const PROFILE: Record<Role, number[]> = {
  //      篮下 中投 三分 篮板 助攻 禁区防 外线防 稳定
  PG: [-6, 3, 5, -14, 13, -12, 6, 0],
  SG: [-2, 5, 8, -12, 2, -9, 5, 0],
  SF: [2, 3, 2, -4, -2, -2, 4, 0],
  PF: [7, 0, -10, 9, -8, 8, -5, 0],
  C: [10, -6, -22, 12, -10, 12, -12, 0],
};
const HEIGHT: Record<Role, [number, number]> = { PG: [180, 193], SG: [188, 201], SF: [198, 206], PF: [203, 211], C: [208, 218] };
const ATTR_KEYS: (keyof Attributes)[] = ['inside', 'mid', 'three', 'rebound', 'assist', 'insideDef', 'outsideDef', 'stability'];

/** 综合能力（与 src/season/db.ts 的 ovr 一致）：八项里最好的六项平均 */
function ovr(at: Attributes): number {
  const v = ATTR_KEYS.map((k) => at[k]).sort((x, y) => y - x);
  return v.slice(0, 6).reduce((s, x) => s + x, 0) / 6;
}

const usedNames = new Set<string>();
let genCount = 0;

function genPlayer(role: Role, targetOvr: number, takenNumbers: Set<number>, teamShorts: Set<string>): DbPlayer {
  let name = '';
  let short = '';
  // 全库不重名，同队不重姓（数据面板只写姓）
  for (let tries = 0; tries < 400; tries++) {
    const g = pick(GIVEN);
    const s = pick(SURNAME);
    name = `${g}·${s}`;
    short = s;
    if (!usedNames.has(name) && !teamShorts.has(s)) break;
  }
  teamShorts.add(short);
  usedNames.add(name);
  // 先按目标值 + 位置偏移 + 噪声生成，再整体平移让综合能力落在目标附近
  const base = targetOvr - 5;
  const raw = PROFILE[role].map((off) => base + off + (rnd() - 0.5) * 12);
  let attrs = Object.fromEntries(ATTR_KEYS.map((k, i) => [k, raw[i]])) as unknown as Attributes;
  const shift = targetOvr - ovr(attrs);
  const fin = (v: number) => Math.max(45, Math.min(95, Math.round(v + shift)));
  attrs = Object.fromEntries(ATTR_KEYS.map((k) => [k, fin(attrs[k])])) as unknown as Attributes;
  const [hLo, hHi] = HEIGHT[role];
  const height = randInt(hLo, hHi);
  let number = randInt(0, 55);
  while (takenNumbers.has(number)) number = randInt(0, 55);
  takenNumbers.add(number);
  genCount++;
  return {
    id: `g${String(genCount).padStart(3, '0')}`,
    name,
    short,
    role,
    height,
    weight: Math.round(height * 0.52 - 4 + randInt(-4, 8)),
    age: randInt(21, 34),
    number,
    sprite: pick(SPRITES),
    legend: false,
    badges: [],
    attrs,
  };
}

