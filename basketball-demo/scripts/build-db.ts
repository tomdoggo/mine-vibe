// ---------- 随机 ----------
let seed = 20261117;
function rnd(): number {
  seed = (seed + 0x6d2b79f5) | 0;
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
const randInt = (lo: number, hi: number) => lo + Math.floor(rnd() * (hi - lo + 1));
const pick = <T>(arr: T[]): T => arr[Math.floor(rnd() * arr.length)];

const SPRITES = [2, 3, 5, 6, 9, 10, 12, 13, 22, 25];

const a = (inside: number, mid: number, three: number, rebound: number, assist: number, insideDef: number, outsideDef: number, stability: number): Attributes => ({
  inside,
  mid,
  three,
  rebound,
  assist,
  insideDef,
  outsideDef,
  stability,
});

