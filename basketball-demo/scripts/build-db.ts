let legendCount = 0;

const ROLES: Role[] = ['PG', 'SG', 'SF', 'PF', 'C'];

/** 生成球员的目标综合能力：[首发, 替补] 区间 */
const FILL_OVR: Record<Tier, { starter: [number, number]; bench: [number, number] }> = {
  elite: { starter: [74, 77], bench: [68, 73] },
  normal: { starter: [67, 71], bench: [60, 66] },
  weak: { starter: [61, 66], bench: [54, 60] },
};

function buildTeam(src: { id: string; name: string; short: string; tier: Tier; color: string; legends: L[]; starters: number }): void {
  const numbers = new Set<number>(src.legends.map((l) => l[6]));
  const shortsUsed = new Set<string>(src.legends.map((l) => l[1]));
  const legendPlayers = src.legends.map((l): DbPlayer => {
    legendCount++;
    return {
      id: `L${String(legendCount).padStart(3, '0')}`,
      name: l[0],
      short: l[1],
      role: l[2],
      height: l[3],
      weight: l[4],
      age: l[5],
      number: l[6],
      sprite: SPRITES[(legendCount * 7) % SPRITES.length],
      legend: true,
      badges: l[8],
      attrs: l[7],
    };
  });
  const starters = legendPlayers.slice(0, src.starters);
  const bench = legendPlayers.slice(src.starters);
  const fill = FILL_OVR[src.tier];
  // 首发补齐五个位置
  const startRoles = new Set(starters.map((p) => p.role));
  for (const r of ROLES) {
    if (starters.length >= 5) break;
    if (startRoles.has(r)) continue;
    starters.push(genPlayer(r, randInt(...fill.starter), numbers, shortsUsed));
    startRoles.add(r);
  }
  // 替补补到 5 人，位置轮流，避免和已有替补重复太多
  const benchRoles = [...ROLES].sort(() => rnd() - 0.5);
  let bi = 0;
  while (starters.length + bench.length < 10) {
    const taken = new Set(bench.map((p) => p.role));
    let r = benchRoles[bi++ % 5];
    for (let k = 0; k < 5 && taken.has(r); k++) r = benchRoles[bi++ % 5];
    bench.push(genPlayer(r, randInt(...fill.bench), numbers, shortsUsed));
  }
  // 首发按 PG SG SF PF C 排，替补按综合能力从高到低
  starters.sort((x, y) => ROLES.indexOf(x.role) - ROLES.indexOf(y.role));
  bench.sort((x, y) => ovr(y.attrs) - ovr(x.attrs));
  const roster = [...starters, ...bench];
  // 同队简称重名时改用全名
  const shorts = new Map<string, number>();
  for (const p of roster) shorts.set(p.short, (shorts.get(p.short) ?? 0) + 1);
  for (const p of roster) if ((shorts.get(p.short) ?? 0) > 1 && !p.legend) p.short = p.name.replace('·', '');
  players.push(...roster);
  teams.push({ id: src.id, name: src.name, short: src.short, tier: src.tier, color: src.color, roster: roster.map((p) => p.id) });
}

for (const t of ELITE) buildTeam(t);
